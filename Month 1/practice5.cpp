#include <iostream>

int main(){

    int decimal = 10;
    int octal = 020;
    int hexadecimal = 0xa23;
    int binary = 0b010101;


    std::cout << "Decimal " << decimal << std::endl;
    
    std::cout << "Octal " << octal << std::endl;

    std::cout << "Hexadecimal " << hexadecimal << std::endl;

    std::cout << "Binary " << binary << std::endl;

    return 0;
}